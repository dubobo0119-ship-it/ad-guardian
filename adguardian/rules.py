# -*- coding: utf-8 -*-
"""违规广告知识库

数据来源(截至 2026 年 8 月,请以官方发布为准):
- 《中华人民共和国广告法》
- 《互联网广告管理办法》(2023 年 5 月 1 日施行)
- 《互联网弹窗信息推送服务管理规定》(2022 年施行)
- 工信部关于 APP 侵害用户权益专项整治的系列通知
  (2022 年整治弹窗关不掉/乱跳转;2023 年禁止高灵敏度"摇一摇";
   2026 年 6 月召开专题会议进一步细化弹窗广告监管红线)

设计说明:
- 每条违规类型 = 用户能看懂的现象描述 + 法规原文依据 + 取证要点 + 举报标签
- 每条渠道 = 受理范围 + 入口 + 操作步骤 + 处理时限
- 举报标签用于 report.py 中自动匹配渠道
"""

from dataclasses import dataclass, field


@dataclass
class ViolationType:
    key: str            # 程序标识
    name: str           # 显示名称
    symptom: str        # 用户视角的现象描述
    basis: list         # 法规依据(逐条列出)
    evidence: list      # 取证要点(怎么把证据固定下来)
    tags: list = field(default_factory=list)  # 举报标签,用于匹配渠道


@dataclass
class ReportChannel:
    key: str            # 程序标识
    name: str           # 渠道名称
    scope: str          # 受理范围
    entry: str          # 入口(网址/小程序/电话)
    steps: list         # 操作步骤
    sla: str            # 处理时限参考
    tags: list          # 擅长处理的举报标签
    go: str = ""        # 直达入口:网址则复制后浏览器打开;小程序名则复制后去微信搜


